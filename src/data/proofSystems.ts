export interface ProofImage {
  src: string;
  alt: string;
  width: number;
  height: number;
  /** กรอบที่ห่อภาพ — browser = แถบ URL ด้านบน · phone = จอมือถือ · plain = ภาพเปล่า */
  frame: 'browser' | 'phone' | 'plain';
  /**
   * ป้ายในแถบบนของกรอบเบราว์เซอร์ (เฉพาะ frame browser)
   * ⛔️ ห้ามใส่ URL หรือชื่อโฮสต์จริงเด็ดขาด — หน้านี้เป็นหน้าสาธารณะ
   *    การประกาศที่อยู่ของระบบหลังบ้านคือการแจกเป้าให้คนสแกนฟรี ๆ
   *    ใส่เป็นคำอธิบายว่าเป็นระบบอะไรพอ
   */
  frameLabel?: string;
  /** มี @700 คู่ไว้ทำ srcset ไหม (ภาพแนวตั้งกว้างไม่ถึง 900 ไม่มี) */
  hasSmall?: boolean;
}

export interface ProofSystem {
  id: string;
  /** ตัวอักษร D.A.R.U.M.A. ที่ระบบนี้พาดถึง */
  letters: string[];
  tagLabel: string;
  title: string;
  /** ฉากชีวิตเจ้าของหลังระบบเข้าที่ ใช้เป็น glance layer บนหน้า Consult */
  consultMoment: string;
  consultOutcome: string;
  /** ชั้นที่ 1 — เกิดอะไรขึ้น */
  what: string;
  /** ชั้นที่ 2 — หลักคิดข้างหลัง */
  whyLead: string;
  whyBody: string;
  /** ชั้นที่ 3 — ถ้าไม่มีระบบนี้จะเจ็บยังไง */
  cost: string;
  /**
   * ภาพกว้าง (screenshot เดสก์ท็อป) อ่านไม่ออกถ้าบีบลงครึ่งการ์ด → 'full' = ข้อความอยู่บน ภาพกินเต็มความกว้าง
   * ภาพแนวตั้ง (จอมือถือ) สูงพอ ๆ กับคอลัมน์ข้อความอยู่แล้ว → 'side' = วางคู่กันซ้าย-ขวา
   */
  mediaWidth: 'full' | 'side';
  images: ProofImage[];
  /** ภาพที่ใช้ตอนโชว์ระบบนี้เดี่ยว ๆ บนหน้า ads (index ใน images) */
  heroImage: number;
  /** ประโยคชวนทัก LINE ต่อท้ายการ์ด — ใส่เฉพาะระบบที่คนถามหาบ่อยว่า "ทำให้ผมได้ไหม" */
  lineCta?: string;
}

